#!/usr/bin/env python3
"""Build blocks/INDEX.md from the YAML frontmatter of every block in blocks/.

The index is what the generator loads whole. Source files are read only when a
block in them is actually wanted. Run this after editing any block file.

Usage: python3 tools/build_index.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOCKS = ROOT / "blocks"
SKIP = {"SCHEMA.md", "INDEX.md"}

# A block is a level-3 heading whose id is the heading text, followed by a
# fenced yaml frontmatter block, optionally followed by a **short:** line.
BLOCK_RE = re.compile(
    r"^### (?P<id>[a-zA-Z0-9_\-]+)\s*\n```yaml\n(?P<yaml>.*?)\n```\n(?P<body>.*?)(?=\n### |\n## |\Z)",
    re.S | re.M,
)


def scalar(yaml_text, key):
    m = re.search(rf"^{key}:\s*(.+)$", yaml_text, re.M)
    if not m:
        return ""
    return m.group(1).strip().strip("'\"")


def listval(yaml_text, key):
    raw = scalar(yaml_text, key)
    if not raw:
        return []
    raw = raw.strip("[]")
    return [v.strip() for v in raw.split(",") if v.strip()]


def first_short(body):
    m = re.search(r"\*\*short:\*\*\s*(.+)", body)
    if not m:
        return ""
    line = m.group(1).strip()
    return line if len(line) <= 160 else line[:157].rstrip() + "..."


def main():
    if not BLOCKS.is_dir():
        sys.exit(f"no blocks directory at {BLOCKS}")

    rows = []
    for path in sorted(BLOCKS.glob("*.md")):
        if path.name in SKIP:
            continue
        text = path.read_text(encoding="utf-8")
        for m in BLOCK_RE.finditer(text):
            y = m.group("yaml")
            rows.append(
                {
                    "id": m.group("id"),
                    "file": path.name,
                    "type": scalar(y, "type"),
                    "lanes": listval(y, "lanes"),
                    "competency": listval(y, "competency"),
                    "register": listval(y, "register"),
                    "strength": scalar(y, "strength"),
                    "claim": first_short(m.group("body")),
                }
            )

    if not rows:
        sys.exit("parsed zero blocks; check the heading and frontmatter format")

    out = []
    out.append("# Block index")
    out.append("")
    out.append(
        "Generated by `tools/build_index.py`. Do not edit by hand. "
        "Re-run after changing any block."
    )
    out.append("")
    out.append(f"{len(rows)} blocks across {len({r['file'] for r in rows})} source files.")
    out.append("")
    out.append(
        "Load this file whole. Read a source file only when you want a block that lives in it. "
        "`claim` is the short variant, truncated. The long variant is in the source file."
    )
    out.append("")

    lanes = sorted({l for r in rows for l in r["lanes"]})
    evidence_types = {"role_summary", "bullet", "project"}
    evidence_rows = [r for r in rows if r["type"] in evidence_types]
    out.append("## Evidence depth by lane")
    out.append("")
    out.append(
        "Counts `role_summary`, `bullet` and `project` blocks only. "
        "Skill terms and identity blocks are tagged for every lane and would flatter the count."
    )
    out.append("")
    out.append("| lane | strong | adequate | thin |")
    out.append("|---|---|---|---|")
    for lane in lanes:
        sub = [r for r in evidence_rows if lane in r["lanes"]]
        counts = {s: sum(1 for r in sub if r["strength"] == s) for s in ("strong", "adequate", "thin")}
        out.append(f"| {lane} | {counts['strong']} | {counts['adequate']} | {counts['thin']} |")
    out.append("")

    out.append("## Blocks")
    out.append("")
    out.append("| id | file | type | lanes | strength | claim |")
    out.append("|---|---|---|---|---|---|")
    for r in rows:
        claim = r["claim"].replace("|", "\\|")
        out.append(
            f"| `{r['id']}` | {r['file']} | {r['type']} | {' '.join(r['lanes'])} | "
            f"{r['strength']} | {claim} |"
        )
    out.append("")

    out.append("## Competency vocabulary")
    out.append("")
    comps = sorted({c for r in rows for c in r["competency"]})
    out.append(", ".join(f"`{c}`" for c in comps))
    out.append("")
    out.append(
        "This vocabulary is what the matcher scores posting requirements against. "
        "Adding a competency to a block adds it here on the next run. Keep it small."
    )
    out.append("")

    (BLOCKS / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {BLOCKS / 'INDEX.md'}: {len(rows)} blocks")


if __name__ == "__main__":
    main()
